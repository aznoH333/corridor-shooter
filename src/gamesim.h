////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//#Game director#
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#define GD_MAX_POINTS 32
typedef struct {
    // a gd point is a point at which the game director can act (spawn enemies/ loot)
    // these are placed at fixed intervals through the level
    // once reached the gd marks them as reached and decides which action to take
    float gdPoints[GD_MAX_POINTS];
    int reached;
    int pointsUsed;
    int patrolTimer;
} GameDirector;


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//#Entities#
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
typedef struct Entity Entity;
typedef struct GameState GameState;

#define ENTITY_DATA_SIZE 4089

// when you multiply a number by this constant you convert from texture coordinates (pixels) to game coordinates
#define TEX_SIZE_TO_GAME 0.03125f


typedef struct {
    char* texture;
    Color color;
    float width;
    float height;
    Vector3 offset;
    float yaw;
    float pitch;
    float roll;
    bool enableDepthMask;
    bool enabled;
} EntityTexture;

EntityTexture noTexture();
EntityTexture simpleTexture(char* texture, float width, float height);
EntityTexture simpleColoredTexture(char* texture, float width, float height, Color color);
EntityTexture rotatedTexture(char* texture, float width, float height, float rotation);
EntityTexture rotatedTextureFull(char* texture, float width, float height, float yaw, float pitch, float roll);


typedef struct {
    bool isLight;
    float radius;
    float r;
    float g;
    float b;
} EntityLight;

typedef enum {
    ENTITY_PLAYER,
    ENTITY_ENEMY,
    ENTITY_BULLET,
    ENTITY_UNSET,
} EntityType;



struct Entity{
    // generic data
    EntityTexture texture;
    float x;
    float y;
    float z;
    float width;
    float height;
    
    EntityLight light;
    EntityType type;

    // entity specific
    char data[ENTITY_DATA_SIZE];
    bool(*update)(Entity*, GameState*);
};

#define MAX_ENTITIES 1000
typedef struct {
    Entity values[MAX_ENTITIES];
    int count;
} GameEntities;

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//#Map and camera#
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

typedef struct {
    float length;
    float width;
    float ceilingHeight;
} GameMap;

typedef struct {
    float distance;
    int screenShake;
} GameCamera;




////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//#Additional rendering#
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#define MAX_ADDITIONAL_PLANES 1000
typedef struct {
    Plane values[MAX_ADDITIONAL_PLANES];
    int count;
} AdditionalPlanes;

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//#User interface#
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
typedef enum {
    MAIN_MENU,
    GAME_PAUSED,
    GAME,
} UIStateName;

typedef struct {
    UIStateName name;
    bool allowEntityUpdates;
    bool drawMouseCursor;
} UIState;

typedef struct {
    // game ui
    float playerHealth;
    float playerHealthMax;
    float playerAmmo;
    float playerAmmoMax;
    float playerReloadPercentage;
    int playerStimCount;
} UIValues;

typedef struct {
    UIState state;
    UIValues uiValues;
    Entity playerEntity; // we store the current player here so we can transition him safely through the levels
    bool shouldWindowLive;
} GameMetaState;




////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
